/**
 * Draws the logo tile used in emails and writes it to lib/email-logo.ts.
 *
 *   node scripts/generate-email-logo.mjs
 *
 * Mail apps in dark mode darken the email but leave images alone, so a plain
 * black logo disappears. The logo is drawn on a white rounded tile instead: it
 * blends into the white card in light mode and shows as a badge in dark mode.
 * The image is stored in the code and attached to each email (cid:eyra-logo),
 * so it needs no hosting and no "display images" click. Run this again if the
 * logo changes (public/images/logo-eyra-black.svg).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { chromium } from "@playwright/test";

const svg = readFileSync("public/images/logo-eyra-black.svg", "utf8");
const TILE = { w: 164, h: 105 }; // size in the email, in CSS pixels
const SCALE = 3; // pixels per CSS pixel, so it is sharp on phones

const browser = await chromium.launch();
const page = await browser.newPage({ deviceScaleFactor: SCALE });
await page.setContent(`<body style="margin:0;background:transparent">
  <div id="tile" style="width:${TILE.w}px;height:${TILE.h}px;background:#fff;border-radius:14px;display:flex;align-items:center;justify-content:center">
    <img width="132" height="77" src="data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}">
  </div></body>`);
await page.waitForFunction(() => document.querySelector("img").complete);
const png = await page.locator("#tile").screenshot({ omitBackground: true });
await browser.close();

writeFileSync(
  "lib/email-logo.ts",
  `/**
 * The EYRA logo on a white tile, as a PNG, for emails. Generated by
 * scripts/generate-email-logo.mjs: do not edit by hand. Displayed at
 * ${TILE.w} x ${TILE.h} px; the image itself is ${SCALE}x that for sharp screens.
 */
export const EMAIL_LOGO_WIDTH = ${TILE.w};
export const EMAIL_LOGO_HEIGHT = ${TILE.h};
export const EMAIL_LOGO_PNG_BASE64 =
  "${png.toString("base64")}";
`
);
console.log(`logo tile written: ${png.length} bytes PNG`);
